"""Add models whose converted chat template matches the official one on every case.

    .venv/bin/python tools/adopt_templates.py MODEL...        (MODEL: org__name, as under ref/models)

For each model it converts the official template (tools/jinja2tsx.py) to
views/third_party/<org>/<model>.tsx, registers it in views/index.json, runs `affordance check`
on it, and keeps it only if every case is exact. For the kept ones it adds the model to
ref/models.txt and writes the folder's NOTICE.md section: the model, the revision the template
was read at, and its license. Needs the reference data (ref/models, ref/out/dev, ref/tokenizers).
"""
import json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jinja2tsx
from huggingface_hub import HfApi

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
# Folders that already exist under another spelling of the organisation's name.
FOLDER = {"XiaomiMiMo": "xiaomi", "meta-models": "meta-muse"}
# Models whose own tokenizer class changes the inputs before the template runs (read from the
# class's `apply_chat_template`): the same change, as the view's first step.
SORTED_TOOLS = {"prepare": "({...given, tools: J.deep_sort(given.tools ?? null)})"}
KIMI_TS = {"prepare": "kimiInputs(given)", "imports": 'import { kimiInputs } from "./tool_declaration_ts.tsx";\n'}
PREPARE = {
    "moonshotai__Kimi-K2.5": KIMI_TS,
    "moonshotai__Kimi-K2.6": KIMI_TS,
    "moonshotai__Kimi-K2.7-Code": KIMI_TS,
    "moonshotai__Kimi-K2-Instruct": SORTED_TOOLS,
    "moonshotai__Kimi-K2-Instruct-0905": SORTED_TOOLS,
    "moonshotai__Kimi-K2-Thinking": SORTED_TOOLS,
    "moonshotai__Kimi-Linear-48B-A3B-Instruct": SORTED_TOOLS,
}
BEGIN, END = "<!-- converted templates: generated by tools/adopt_templates.py -->", "<!-- end converted templates -->"


def folder(org): return FOLDER.get(org, org.lower())
def filename(model): return re.sub(r"[^A-Za-z0-9_.-]", "_", model.split("__", 1)[1]) + ".tsx"


def template(name):
    d = "ref/models/" + name
    for f in ["chat_template.jinja", "tokenizer_config.json", "chat_template.json"]:
        p = os.path.join(d, f)
        if not os.path.exists(p): continue
        raw = open(p).read()
        if f.endswith(".jinja"): return raw
        t = json.loads(raw).get("chat_template")
        if isinstance(t, list): t = {x["name"]: x["template"] for x in t}
        if t: return t
    return None


def check(names):
    """model -> 'exact' or what differed."""
    results = {}
    def read(out, wanted):
        for line in out.splitlines():
            m = re.match(r"(\S+)\s+(\d+)/\s*(\d+) exact \(\d+ match, (\d+) both-error, (\d+) same kind\)\s+mismatch (\d+)\s+unexpected-error (\d+)\s+missing-error (\d+)", line)
            if m and m.group(1) in wanted:
                if m.group(2) != m.group(3): results[m.group(1)] = f"{m.group(2)} of {m.group(3)} cases (mismatch {m.group(6)}, our error {m.group(7)}, their error {m.group(8)})"
                elif m.group(4) != m.group(5): results[m.group(1)] = f"{int(m.group(4)) - int(m.group(5))} cases fail for a different kind of reason than the official template"
                else: results[m.group(1)] = "exact"
            m = re.match(r"(\S+)\s+LOAD ERROR (.*)", line)
            if m and m.group(1) in wanted: results[m.group(1)] = "load error: " + m.group(2)[-120:]
    for i in range(0, len(names), 40):
        chunk = names[i:i + 40]
        read(subprocess.run(["./target/release/affordance", "check", "--only", ",".join(chunk)], capture_output=True, text=True).stdout, chunk)
        for name in chunk:
            if name in results: continue
            one = subprocess.run(["./target/release/affordance", "check", "--only", name], capture_output=True, text=True)
            read(one.stdout, [name])
            if name not in results:
                err = [l for l in one.stderr.splitlines() if l.strip() and "RUST_BACKTRACE" not in l]
                results[name] = "check stopped: " + (err[-1][:140] if err else "no output")
    return results


def notices(index):
    """Rewrite each third-party folder's section listing its converted templates."""
    meta_path = "views/third_party/converted.json"
    meta = json.load(open(meta_path)) if os.path.exists(meta_path) else {}
    api = HfApi()
    by_folder = {}
    for model, entry in index.items():
        if model.startswith("_") or not entry.get("converted"): continue
        repo = model.replace("__", "/", 1)
        if repo not in meta:
            info = api.model_info(repo)
            card = info.card_data.to_dict() if info.card_data else {}
            meta[repo] = {"revision": info.sha[:12], "license": card.get("license_name") or card.get("license") or "not stated", "license_link": card.get("license_link")}
        by_folder.setdefault(entry["view"].split("/")[1], []).append((repo, entry["view"].split("/")[-1], meta[repo]))
    json.dump(meta, open(meta_path, "w"), indent=1, sort_keys=True)
    for name, items in by_folder.items():
        lines = [BEGIN, "", "## Converted chat templates", "",
                 "Each file below is the chat template of the model named, converted to TSX by",
                 "`tools/jinja2tsx.py`. Its text is the template's own.", ""]
        for repo, file, m in sorted(items):
            link = m["license_link"] if isinstance(m["license_link"], str) and m["license_link"].startswith("http") else f"https://huggingface.co/{repo}"
            lines.append(f"- `{file}`: [{repo}](https://huggingface.co/{repo}/tree/{m['revision']}) at revision `{m['revision']}`. License: [{m['license']}]({link}).")
        lines += ["", "These files are not licensed under this repository's Apache-2.0 license; each model's own",
                  "license governs the text of its template.", "", END]
        path = f"views/third_party/{name}/NOTICE.md"
        old = open(path).read() if os.path.exists(path) else f"# {name} chat-template text\n"
        if BEGIN in old: old = old[:old.index(BEGIN)].rstrip("\n") + "\n" + old[old.index(END) + len(END):].lstrip("\n")
        open(path, "w").write(old.rstrip("\n") + "\n\n" + "\n".join(lines) + "\n")


def main(names):
    index_path = "views/index.json"
    index = json.load(open(index_path))
    before = dict(index)
    report, trying = {}, []
    for name in names:
        org = name.split("__", 1)[0]
        # A model with a hand-written view keeps it.
        if name in before and not before[name]["view"].startswith("third_party/"): report[name] = "already has a hand-written view"; continue
        if not os.path.exists(f"ref/out/dev/{name}.json"): report[name] = "no official reference"; continue
        t = template(name)
        if not t: report[name] = "no chat template"; continue
        try:
            source = jinja2tsx.convert(t, name.replace("__", "/", 1), runtime="../../common/jinja.tsx", **PREPARE.get(name, {}))
        except jinja2tsx.Unsupported as e:
            report[name] = f"converter does not handle {e}"; continue
        except Exception as e:
            report[name] = f"converter failed: {type(e).__name__}: {str(e)[:100]}"; continue
        d = f"views/third_party/{folder(org)}"
        os.makedirs(d, exist_ok=True)
        open(f"{d}/{filename(name)}", "w").write(source)
        index[name] = {"view": f"third_party/{folder(org)}/{filename(name)}", "entry": "Main", "converted": True}
        trying.append(name)
    open(index_path, "w").write(json.dumps(index, indent=1) + "\n")
    results = check(trying)
    kept = []
    for name in trying:
        report[name] = results[name]
        if results[name] == "exact": kept.append(name); continue
        os.remove("views/" + index[name]["view"])
        if name in before: index[name] = before[name]
        else: del index[name]
    for d in os.listdir("views/third_party"):
        p = os.path.join("views/third_party", d)
        if os.path.isdir(p) and not os.listdir(p): os.rmdir(p)
    open(index_path, "w").write(json.dumps(index, indent=1) + "\n")
    listed = open("ref/models.txt").read()
    with open("ref/models.txt", "a") as f:
        for name in kept:
            repo = name.replace("__", "/", 1)
            if f"| {repo}\n" not in listed: f.write(f"converted | {repo}\n")
    notices(index)
    json.dump(report, open("target/adopt_report.json", "w"), indent=1)
    print(f"{len(kept)} of {len(names)} adopted")
    for name in names:
        if report[name] != "exact": print(f"  {name}: {report[name]}")


if __name__ == "__main__":
    main(sys.argv[1:])
